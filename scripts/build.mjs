// Builds dist/ from tokens/. Run: npm run build
import { mkdirSync, writeFileSync, readFileSync, readdirSync, copyFileSync } from 'node:fs';
import { readJsonTree, load, resolve, cssName, cssValue, refOrValue } from './lib.mjs';

const primitiveFiles = readJsonTree('tokens/primitive');
const sharedSemanticFiles = readJsonTree('tokens/semantic').filter((f) => !f.includes('/themes/'));
const themes = readdirSync('tokens/semantic/themes').filter((f) => f.endsWith('.json')).map((f) => f.replace('.json', ''))
  .sort((a, b) => (a === 'light' ? -1 : b === 'light' ? 1 : a.localeCompare(b))); // light first: later themes must win over :root
if (!themes.includes('light')) throw new Error('tokens/semantic/themes/light.json is required (default theme).');

const base = load([...primitiveFiles, ...sharedSemanticFiles]);
const themed = Object.fromEntries(themes.map((t) => [t, load([`tokens/semantic/themes/${t}.json`])]));
const all = { ...base, ...themed.light };

mkdirSync('dist', { recursive: true });
const header = '/* Generated by scripts/build.mjs from tokens/. Do not edit by hand. */\n';

// 1. tokens.css: primitives + shared semantic in :root, each theme in its own selector.
let css = header + ':root {\n';
for (const [k, t] of Object.entries(base)) css += `  ${cssName(k)}: ${refOrValue(base, t.value)};\n`;
css += '}\n\n';
for (const t of themes) {
  const sel = t === 'light' ? ':root, [data-theme="light"]' : `[data-theme="${t}"]`;
  css += `${sel} {\n`;
  if (t !== 'light') css += '  color-scheme: dark;\n';
  for (const [k, tok] of Object.entries(themed[t])) css += `  ${cssName(k)}: ${refOrValue({ ...base, ...themed[t] }, tok.value)};\n`;
  css += '}\n\n';
  // data-theme="system" follows the device setting (used until the person picks a theme with the switch).
  if (t === 'dark') {
    css += '@media (prefers-color-scheme: dark) {\n  [data-theme="system"] {\n    color-scheme: dark;\n';
    for (const [k, tok] of Object.entries(themed[t])) css += `    ${cssName(k)}: ${refOrValue({ ...base, ...themed[t] }, tok.value)};\n`;
    css += '  }\n}\n\n';
  }
}
writeFileSync('dist/tokens.css', css);

// 2. tailwind.css: Tailwind v4 theme exposing ONLY semantic roles, fonts, spacing, radius, breakpoints.
const semanticColors = Object.keys(themed.light).filter((k) => k.startsWith('color.'));
let tw = header + '@import "./tokens.css";\n\n@theme inline {\n  --color-*: initial;\n';
for (const k of semanticColors) tw += `  --color-${k.slice(6).replace(/\./g, '-')}: var(${cssName(k)});\n`;
tw += `  --font-heading: var(${cssName('font.family.heading')});\n  --font-body: var(${cssName('font.family.body')});\n  --font-sans: var(${cssName('font.family.body')});\n`;
for (const k of Object.keys(base).filter((k) => k.startsWith('space.'))) tw += `  --spacing-${k.slice(6)}: var(${cssName(k)});\n`;
for (const k of Object.keys(base).filter((k) => k.startsWith('radius.'))) tw += `  --radius-${k.slice(7)}: var(${cssName(k)});\n`;
// Breakpoints must be literal values: Tailwind cannot use var() inside media queries.
for (const k of Object.keys(base).filter((k) => k.startsWith('breakpoint.'))) tw += `  --breakpoint-${k.slice(11)}: ${resolve(base, base[k].value)};\n`;
for (const k of Object.keys(base).filter((k) => k.startsWith('font.size.'))) tw += `  --text-${k.slice(10)}: var(${cssName(k)});\n`;
// Short class names: text-muted, bg-subtle, border-strong (the long forms text-text-muted etc. keep working).
for (const k of semanticColors.filter((k) => k.startsWith('color.text.'))) tw += `  --text-color-${k.slice(11)}: var(${cssName(k)});\n`;
for (const k of semanticColors.filter((k) => k.startsWith('color.surface.'))) tw += `  --background-color-${k.slice(14)}: var(${cssName(k)});\n`;
for (const k of semanticColors.filter((k) => k.startsWith('color.border.'))) tw += `  --border-color-${k.slice(13)}: var(${cssName(k)});\n`;
tw += `  --ease-standard: var(${cssName('easing.standard')});\n`;
tw += '}\n';
// Text styles as one class each: type-h1, type-body, type-label ...
const styleNames = [...new Set(Object.keys(base).filter((k) => k.startsWith('text-style.')).map((k) => k.split('.')[1]))];
for (const n of styleNames) {
  const v = (part) => `var(${cssName(`text-style.${n}.${part}`)})`;
  tw += `\n@utility type-${n} {\n  font-family: ${v('family')};\n  font-weight: ${v('weight')};\n  font-size: ${v('size')};\n  line-height: ${v('line-height')};\n}\n`;
}
writeFileSync('dist/tailwind.css', tw);

// 3. tokens.json: every token resolved to a final value (light theme), for agents and non-CSS tools.
const flat = {};
for (const [k, t] of Object.entries(all)) flat[k] = { value: resolve(all, t.value), ...(t.description ? { description: t.description } : {}) };
writeFileSync('dist/tokens.json', JSON.stringify(flat, null, 2) + '\n');

// 4. fonts: self-hosted Barlow and Barlow Condensed (no requests to Google).
mkdirSync('dist/fonts', { recursive: true });
for (const f of readdirSync('fonts')) {
  if (f.endsWith('.woff2') || f === 'OFL.txt') copyFileSync(`fonts/${f}`, `dist/fonts/${f}`);
}
copyFileSync('fonts/fonts.css', 'dist/fonts.css');

// 5. components.css: base first, then each component (plain CSS on semantic tokens; works with or without Tailwind).
const componentFiles = readdirSync('components').filter((f) => f.endsWith('.css')).sort((a, b) => (a === 'base.css' ? -1 : b === 'base.css' ? 1 : a.localeCompare(b)));
writeFileSync('dist/components.css', header + componentFiles.map((f) => readFileSync(`components/${f}`, 'utf8').trim()).join('\n\n') + '\n');

// Behavior script for plain HTML pages (tabs, dialogs).
copyFileSync('behavior/isa.js', 'dist/isa.js');

// 6. preview.html: live examples of every component, then every color role. Built from the same files projects use.
const v = (k) => resolve(all, all[k].value);
const examples = readdirSync('components').filter((f) => f.endsWith('.examples.html')).sort()
  .map((f) => `<section><h2>${f.replace('.examples.html', '').replace(/^./, (c) => c.toUpperCase()).replace('Field', 'Form fields').replace('Navigation', 'Header, navigation and footer').replace('Empty', 'Empty state').replace('Page', 'Page layout')}</h2>\n${readFileSync(`components/${f}`, 'utf8')}</section>`).join('\n');
const dark = themed.dark ? { ...base, ...themed.dark } : null;
const sw = (c) => `<span class="sw" style="background:${c}"></span> <code>${c}</code>`;
const rows = semanticColors.map((k) => `<tr><td><code>${k}</code></td><td>${sw(v(k))}</td>${dark ? `<td>${sw(resolve(dark, dark[k].value))}</td>` : ''}<td>${all[k].description ?? ''}</td></tr>`).join('\n');
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>ISA Design System preview</title>
<link rel="stylesheet" href="./fonts.css"><link rel="stylesheet" href="./tokens.css"><link rel="stylesheet" href="./components.css">
<style>
body{margin:0;font-family:var(--isa-font-family-body);color:var(--isa-color-text-default);background:var(--isa-color-surface-default);line-height:var(--isa-font-line-height-normal)}
main{max-width:72rem;margin:0 auto;padding:var(--isa-space-8) var(--isa-space-4)}
h1,h2,h3{font-family:var(--isa-font-family-heading);line-height:var(--isa-font-line-height-snug);margin:0}
h1{font-size:var(--isa-font-size-5xl)}section>h2{font-size:var(--isa-font-size-4xl);margin-top:var(--isa-space-12);padding-top:var(--isa-space-6);border-top:1px solid var(--isa-color-border-default)}
h3{font-size:var(--isa-font-size-xl);font-weight:var(--isa-font-weight-semibold);margin-top:var(--isa-space-6)}section>h3{margin-bottom:var(--isa-space-3)}
.row{display:flex;flex-wrap:wrap;gap:var(--isa-space-3);align-items:center;margin-top:var(--isa-space-3)}

.stack{display:grid;gap:var(--isa-space-3);margin-top:var(--isa-space-4);max-width:40rem}.form{display:grid;gap:var(--isa-space-5);margin-top:var(--isa-space-4);max-width:28rem}
.brand{background:var(--isa-color-surface-brand);padding:var(--isa-space-4);border-radius:var(--isa-radius-lg)}
.scroll{overflow-x:auto}table{border-collapse:collapse;width:100%;font-size:var(--isa-font-size-sm);margin-top:var(--isa-space-4)}
th{text-align:left;padding:var(--isa-space-2)}td{border-bottom:1px solid var(--isa-color-border-default);padding:var(--isa-space-2);vertical-align:middle}
.sw{display:inline-block;width:2.5rem;height:1.5rem;border-radius:var(--isa-radius-sm);border:1px solid var(--isa-color-border-default)}
</style></head>
<body><main><div class="row" style="justify-content:space-between"><h1>ISA Design System</h1><button type="button" class="isa-button isa-button--neutral" data-isa-theme-toggle aria-pressed="false"><svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="9"/><path d="M12 3v18M12 7l5 -2M12 12h9M12 17l5 2" /></svg>Dark mode</button></div><p>Version ${JSON.parse(readFileSync('package.json', 'utf8')).version}. Live examples built from the same CSS that projects install. Press Tab to see focus rings.</p>
${examples}
<section><h2>Color roles</h2><p>Run <code>npm run check</code> for contrast results in every theme.</p><div class="scroll"><table><thead><tr><th>Role</th><th>Light</th>${dark ? '<th>Dark</th>' : ''}<th>Use</th></tr></thead>${rows}</table></div></section>
</main><script type="module">
${readFileSync('behavior/isa.js', 'utf8').replace(/^export /gm, '')}</script></body></html>
`;
writeFileSync('dist/preview.html', html);

console.log(`Built ${Object.keys(all).length} tokens, themes: ${themes.join(', ')}`);
